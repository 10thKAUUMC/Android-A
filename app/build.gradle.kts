// 릴리즈 서명 정보 로드 — keystore.properties는 .gitignore 처리되어 저장소에 올라가지 않는다.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        load(keystorePropertiesFile.inputStream())
    }
}

// API 키는 소스에 박지 않고 local.properties(.gitignore)에서 읽어 BuildConfig로 주입한다.
val localPropertiesFile = rootProject.file("local.properties")
val localProperties = Properties().apply {
    if (localPropertiesFile.exists()) {
        load(localPropertiesFile.inputStream())
    }
}
val reqResApiKey: String = localProperties.getProperty("REQRES_API_KEY", "")

android {
    namespace = "com.example.umc3"
    compileSdk {
